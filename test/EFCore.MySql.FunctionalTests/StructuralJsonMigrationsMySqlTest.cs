public abstract class StructuralJsonMigrationsTestBase<TFixture>(TFixture fixture)
    : IClassFixture<TFixture>
    where TFixture : StructuralJsonMigrationsFixtureBase, new()
{
    protected TFixture Fixture { get; } = fixture;

    protected virtual bool NoBackslashEscapes
        => false;

    [Fact]
    public void Structural_json_literals_use_provider_escaping()
    {
        using var context = Fixture.CreateContext();
        var literal = context.Model.GetRelationalModel().Tables
            .Single(table => table.Name == "Documents")
            .FindColumn("Settings")!
            .StoreTypeMapping
            .GenerateSqlLiteral(StructuralJsonMigrationData.InitialJson);

        var expected = AppConfig.ServerVersion.Supports.JsonDataTypeEmulation
            ? NoBackslashEscapes
                ? """'{"Description":"O''Reilly \\ archive — 初始 😀"}'"""
                : """'{"Description":"O''Reilly \\\\ archive — 初始 😀"}'"""
            : NoBackslashEscapes
                ? """CAST('{"Description":"O''Reilly \\ archive — 初始 😀"}' AS json)"""
                : """CAST('{"Description":"O''Reilly \\\\ archive — 初始 😀"}' AS json)""";

        Assert.Equal(expected, literal);
    }

    [Fact]
    public async Task Structural_json_literals_execute_on_the_configured_server()
    {
        await using var context = Fixture.CreateContext();
        var literal = context.Model.GetRelationalModel().Tables
            .Single(table => table.Name == "Documents")
            .FindColumn("Settings")!
            .StoreTypeMapping
            .GenerateSqlLiteral(StructuralJsonMigrationData.InitialJson);

        // The SQL literal is generated by the provider from a fixed test value.
        await context.Database.OpenConnectionAsync();
        await using var command = context.Database.GetDbConnection().CreateCommand();
        command.CommandText = "SELECT " + literal + " AS `Value`";
        var result = (string)await command.ExecuteScalarAsync();

        Assert.Equal(
            AppConfig.ServerVersion.Supports.JsonDataTypeEmulation
                ? StructuralJsonMigrationData.InitialJson
                : StructuralJsonMigrationData.MySqlCanonicalJson,
            result);
    }

    [Fact]
    public async Task Migrations_insert_and_update_structural_json_data()
    {
        await using (var context = Fixture.CreateContext())
        {
            await context.Database.EnsureDeletedAsync();
            Assert.Equal(
                "json",
                context.Model.GetRelationalModel().Tables
                    .Single(table => table.Name == "Documents")
                    .FindColumn("Settings")!
                    .StoreType);

            await context.Database.MigrateAsync("20260902000100_CreateStructuralJsonDocuments");
        }

        await using (var context = Fixture.CreateContext())
        {
            var document = await context.Documents.SingleAsync();
            Assert.Equal(StructuralJsonMigrationData.InitialDescription, document.Settings!.Description);

            await context.Database.MigrateAsync("20260902000200_UpdateStructuralJsonDocuments");
        }

        await using var verificationContext = Fixture.CreateContext();
        var updatedDocument = await verificationContext.Documents.SingleAsync();
        Assert.Equal(string.Empty, updatedDocument.Settings!.Description);
    }
}

