    internal const string UpdatedJson = """{"Description":""}""";
}

public sealed class StructuralJsonMigrationsContext(DbContextOptions options) : DbContext(options)
{
    public DbSet<StructuralJsonMigrationDocument> Documents
        => Set<StructuralJsonMigrationDocument>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
        => modelBuilder.Entity<StructuralJsonMigrationDocument>(builder =>
        {
            builder.Property(document => document.Id).ValueGeneratedNever();
            builder.OwnsOne(
                document => document.Settings,
                ownedBuilder => ownedBuilder.ToJson());
        });
}

public sealed class StructuralJsonMigrationDocument
{
    public int Id { get; set; }
    public StructuralJsonMigrationSettings Settings { get; set; } = null!;
}

